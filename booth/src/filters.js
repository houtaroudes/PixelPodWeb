/*
 * The six looks, as arithmetic on pixels.
 *
 * The booth used to get these two ways: a CSS class on the live preview, and a
 * `ctx.filter` chain on the captured frame. Both work by different rules in
 * different browsers, and `ctx.filter` is missing entirely in Safari before 17,
 * so the same look could come out of the live view and the saved photo looking
 * unlike each other. This module is one implementation of the same maths, used
 * for both, so the preview and the file agree.
 *
 * Each chain below is copied from the booth's own style block, function for
 * function and in the order written there. CSS filter functions do not commute,
 * so that order is the specification, not a detail.
 */

/*
 * The names and slugs are the ones the booth already used. `black_white` is the
 * one the PHP generated by accident and never handled: its slugifier turns a
 * space into `_` and deletes `&`, so a filter named "Black & White" became
 * `black__white`, which matches no key in the old filter maps. The static list
 * has no such gap, which is why this table is the source of truth now.
 */
export const FILTERS = [
  { id: 'natural', name: 'Natural', css: null, chain: [] },
  { id: 'black_white', name: 'Black & White', css: 'filter-bw', chain: [['grayscale', 1]] },
  { id: 'vintage', name: 'Vintage', css: 'filter-vintage', chain: [['sepia', 0.6], ['contrast', 0.9], ['brightness', 1.1]] },
  { id: 'glam', name: 'Glam', css: 'filter-glam', chain: [['brightness', 1.15], ['contrast', 1.05], ['saturate', 1.2]] },
  { id: 'film_grain', name: 'Film Grain', css: 'filter-film', chain: [['grayscale', 0.3], ['contrast', 1.1], ['brightness', 0.95]] },
  { id: 'vivid_pop', name: 'Vivid Pop', css: 'filter-vivid', chain: [['saturate', 2], ['contrast', 1.1]] },
]

export const DEFAULT_FILTER = 'natural'

/** The CSS class the live preview wears for a look, or null for Natural. */
export function cssClassFor(id) {
  return FILTERS.find((f) => f.id === id)?.css ?? null
}

/** The label shown in the camera panel, matching the pill the visitor tapped. */
export function nameFor(id) {
  return FILTERS.find((f) => f.id === id)?.name ?? FILTERS[0].name
}

/** The chain of filter functions for a look, in the order they apply. */
export function chainFor(id) {
  return FILTERS.find((f) => f.id === id)?.chain ?? []
}

// Rec. 709 luma coefficients, which is what the grayscale matrix uses.
const LUMA = [0.2126, 0.7152, 0.0722]

/*
 * The primitives. Each takes the three channels and returns three new ones,
 * so nothing reads a channel another step has already overwritten.
 */
const PRIMITIVES = {
  grayscale([r, g, b], amount) {
    const l = LUMA[0] * r + LUMA[1] * g + LUMA[2] * b
    return [r + amount * (l - r), g + amount * (l - g), b + amount * (l - b)]
  },
  sepia([r, g, b], amount) {
    const sr = 0.393 * r + 0.769 * g + 0.189 * b
    const sg = 0.349 * r + 0.686 * g + 0.168 * b
    const sb = 0.272 * r + 0.534 * g + 0.131 * b
    return [r + amount * (sr - r), g + amount * (sg - g), b + amount * (sb - b)]
  },
  saturate([r, g, b], amount) {
    return [
      (0.213 + 0.787 * amount) * r + (0.715 - 0.715 * amount) * g + (0.072 - 0.072 * amount) * b,
      (0.213 - 0.213 * amount) * r + (0.715 + 0.285 * amount) * g + (0.072 - 0.072 * amount) * b,
      (0.213 - 0.213 * amount) * r + (0.715 - 0.715 * amount) * g + (0.072 + 0.928 * amount) * b,
    ]
  },
  brightness([r, g, b], amount) {
    return [r * amount, g * amount, b * amount]
  },
  contrast([r, g, b], amount) {
    // CSS contrast is a slope about mid grey: out = (in - 0.5) * c + 0.5.
    const intercept = 127.5 * (1 - amount)
    return [r * amount + intercept, g * amount + intercept, b * amount + intercept]
  },
}

/*
 * Each CSS filter function is an SVG filter primitive, and a primitive's output
 * is clamped to the range before the next one reads it. That clamp is load
 * bearing: white through Film Grain comes out at 242, not 254, because the
 * contrast step overshoots and the brightness step then multiplies the clamped
 * value. Leaving it out drifted a channel by 12.
 *
 * The channels stay in floating point between steps and are rounded once, by
 * the 8-bit store at the end, which is where the browser rounds too. The golden
 * values in the test were painted by Chrome, and every one of them now lands
 * within one of this implementation.
 */
export function applyTo(imageData, id) {
  const chain = chainFor(id)
  if (!chain.length) return imageData
  const data = imageData.data

  for (let i = 0; i < data.length; i += 4) {
    let px = [data[i], data[i + 1], data[i + 2]]
    for (const [name, amount] of chain) px = clampChannels(PRIMITIVES[name](px, amount))
    // Alpha is deliberately untouched: the frames are opaque, and a look has no
    // business changing how solid the paper is.
    data[i] = px[0]
    data[i + 1] = px[1]
    data[i + 2] = px[2]
  }
  return imageData
}

function clampChannels([r, g, b]) {
  return [r < 0 ? 0 : r > 255 ? 255 : r, g < 0 ? 0 : g > 255 ? 255 : g, b < 0 ? 0 : b > 255 ? 255 : b]
}

/** Applies a look to a whole canvas in place, the way a captured frame is made. */
export function applyToCanvas(canvas, id) {
  if (!chainFor(id).length) return canvas
  const ctx = canvas.getContext('2d')
  const pixels = ctx.getImageData(0, 0, canvas.width, canvas.height)
  applyTo(pixels, id)
  ctx.putImageData(pixels, 0, 0)
  return canvas
}
